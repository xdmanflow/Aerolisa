"""ModelAdapter for the engine-health bundle (Foundry Model Training template, ``adapter.py``).

The adapter is the contract between Foundry and the model: how to save/load it
(``auto_serialize``), what it takes and returns (``api``), and how to run it (``predict``).
The bundle itself is ``aerolisa.engine_health.bundle.EngineHealthBundle`` (vendored copy of
``src/aerolisa``, see scripts/sync_foundry.py), so Foundry runs the exact tested code.

Import paths of palantir_models change across releases: if an import below fails, copy
the import lines from the example adapter generated by your template.
"""

import palantir_models as pm
from palantir_models.serializers import DillSerializer

from aerolisa.core.schema import INFORMATIVE_SENSORS
from aerolisa.engine_health.bundle import SNAPSHOT_COLUMNS, EngineHealthBundle

FEATURES = ["cycle"] + [f"{s}_{k}" for s in INFORMATIVE_SENSORS for k in ("mean", "std", "slope")]
RAW = list(INFORMATIVE_SENSORS)  # anomaly score uses the raw cycle readings


class EngineHealthAdapter(pm.ModelAdapter):
    @pm.auto_serialize(bundle=DillSerializer())
    def __init__(self, bundle: EngineHealthBundle):
        self.bundle = bundle

    @classmethod
    def api(cls):
        inputs = {
            "df_in": pm.Pandas(columns=[("engine_id", str), ("cycle_id", str)]
                               + [(c, float) for c in FEATURES if c != "cycle"] + [("cycle", int)]
                               + [(s, float) for s in RAW]),
        }
        outputs = {
            "df_out": pm.Pandas(columns=[("engine_id", str), ("cycle_id", str), ("cycle", int),
                                         ("rul_p10", float), ("rul_p50", float), ("rul_p90", float),
                                         ("health_index", float), ("anomaly_score", float),
                                         ("top_drivers", str), ("alert", bool), ("model_version", str)]),
        }
        return inputs, outputs

    def predict(self, df_in):
        out = self.bundle.predict(df_in)
        return out[["engine_id", "cycle_id", "cycle", *SNAPSHOT_COLUMNS]]
