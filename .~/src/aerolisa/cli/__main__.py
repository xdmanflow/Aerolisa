"""``python -m aerolisa.cli build | lineage | catalog``"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from aerolisa.cli import graph  # noqa: F401  (registers every transform)
from aerolisa.core.transforms import REGISTRY, build, build_order, lineage_mermaid


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="aerolisa")
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="build datasets and their upstream dependencies")
    b.add_argument("targets", nargs="*", help="dataset names; default: everything")
    sub.add_parser("lineage", help="write docs/lineage.md (Mermaid)")
    sub.add_parser("catalog", help="list datasets in build order")
    a = p.parse_args(argv)
    if a.cmd == "build":
        build(a.targets or None)
    elif a.cmd == "lineage":
        out = Path(__file__).resolve().parents[3] / "docs" / "lineage.md"
        out.write_text("# Lineage (generated by `python -m aerolisa.cli lineage`)\n\n```mermaid\n" + lineage_mermaid() + "\n```\n")
        print(f"wrote {out}")
    else:
        for name in build_order():
            t = REGISTRY[name]
            print(f"{name:<40} <- {', '.join(i.path for i in t.inputs.values()) or '(source)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
